"""Local result notifications. Durable SMTP claims prevent uncertain sends from being repeated."""
from contextlib import closing
from datetime import datetime, timezone, timedelta
from email.message import EmailMessage
from pathlib import Path
import json
import os
import smtplib
from typing import Literal
import urllib.request
from urllib.parse import quote, urlparse
from uuid import UUID, uuid4

from fastapi import HTTPException, Request
from fastapi.responses import FileResponse

from backend.export_register import ExportBatches
from backend.review_events import ReviewEvents, protect_event, send_event
from backend.reviews import protect_write

Kind = Literal['review', 'batch']
LIMIT = 5


def local_smtp(message):
    host = os.environ.get('AP_MAILPIT_HOST', 'mailpit')
    if host not in ('mailpit', 'localhost', '127.0.0.1'):
        return 'failed', 'LOCAL_SMTP_REQUIRED'
    smtp, sending = None, False
    try:
        smtp = smtplib.SMTP(host, 1025, timeout=10)
        sending = True
        refused = smtp.send_message(message)
        return ('failed', 'SMTP_RECIPIENT_REJECTED') if refused else ('sent', None)
    except (smtplib.SMTPRecipientsRefused, smtplib.SMTPSenderRefused, smtplib.SMTPDataError):
        return 'failed', 'SMTP_REJECTED'
    except (OSError, smtplib.SMTPException):
        return ('unknown', 'SMTP_DELIVERY_UNCERTAIN') if sending else ('failed', 'SMTP_CONNECTION_FAILED')
    finally:
        if smtp:
            smtp.close()


class Outcomes:
    def __init__(self, connect, root, sender=local_smtp):
        self.connect, self.sender = connect, sender
        self.events, self.batches = ReviewEvents(connect), ExportBatches(connect, root)

    def context(self, kind, identifier):
        base = os.environ.get('AP_PUBLIC_BASE_URL', 'http://127.0.0.1:8000').rstrip('/')
        parsed = urlparse(base)
        if parsed.scheme != 'http' or parsed.hostname not in ('127.0.0.1', 'localhost') or parsed.username or parsed.query or parsed.fragment:
            raise HTTPException(503, 'Configure a local public review URL.')
        if kind == 'review':
            with closing(self.connect()) as db:
                event, task, _ = self.events.load(db, identifier)
            category = 'review_' + event['event_type']
            subject = '[AP Result] ' + event['event_type'].capitalize() + ' — ' + event['invoice_id']
            lines = [f"Invoice: {event['invoice_id']}", f"Decision: {event['event_type']}",
                     f"Approved revision: {event['review_revision']}" if event['event_type'] == 'approved' else f"Review revision: {event['review_revision']}",
                     f"Decision method: {task['approval_method']}", f"Review: {base}/reviews/{event['invoice_id']}",
                     f'Export register: {base}/exports' if event['event_type'] == 'approved' else 'Rejected invoices cannot be exported.',
                     'Select approved invoices in the export register to download a combined Excel file. No file is generated by this approval.' if event['event_type'] == 'approved' else 'No Excel export was created for this rejection.']
        else:
            batch = self.batches.read(identifier)
            if not batch['download_url']:
                raise HTTPException(409, 'Verify or recover the batch file before notifying.')
            category, subject = 'batch_completed', '[AP Export] Combined Excel ready — ' + identifier
            lines = [f'Export ID: {identifier}', f"Invoices: {batch['row_count']}",
                     f"Download: {base}{batch['download_url']}", f'Export register: {base}/exports',
                     'This file contains the saved approved revisions selected for this batch.']
        return {'kind': kind, 'id': identifier, 'category': category, 'subject': subject,
                'text': '\n'.join(lines + ['Local demonstration. Not submitted to an accounting system; no payment has occurred.'])}

    def read(self, kind, identifier):
        column = 'event_id' if kind == 'review' else 'export_id'
        with closing(self.connect()) as db:
            row = db.execute(f'SELECT * FROM outcome_notifications WHERE {column}=?', (identifier,)).fetchone()
            result = dict(row) if row else {'status': 'not_started', 'attempts': 0}
        return {**result, 'kind': kind, 'id': identifier, 'max_attempts': LIMIT}

    def ensure(self, kind, identifier):
        context = self.context(kind, identifier)
        column = 'event_id' if kind == 'review' else 'export_id'
        with closing(self.connect()) as db:
            db.execute(f'INSERT INTO outcome_notifications(notification_id,{column},category) VALUES(?,?,?) ON CONFLICT({column}) DO NOTHING',
                       (str(uuid4()), identifier, context['category']))
            db.commit()
        return context

    def finish(self, db, row, status, error):
        current = db.execute('SELECT status,attempts,message_id FROM outcome_notifications WHERE notification_id=?', (row['notification_id'],)).fetchone()
        if current['status'] == 'sent' or current['attempts'] != row['attempts'] or current['message_id'] != row['message_id']:
            return  # A delayed worker cannot downgrade confirmed delivery or overwrite a newer attempt.
        now = datetime.now(timezone.utc).isoformat()
        db.execute('UPDATE outcome_notification_attempts SET status=?,error_code=?,updated_at=? WHERE notification_id=? AND attempt=?',
                   (status, error, now, row['notification_id'], row['attempts']))
        db.execute("""UPDATE outcome_notifications SET status=?,last_error=?,updated_at=?,
                   delivery_status=CASE WHEN ?='sent' THEN 'processed' ELSE delivery_status END WHERE notification_id=?""",
                   (status, error, now, status, row['notification_id']))
        if status == 'sent' and row['event_id']:
            # SMTP confirmation, not webhook acceptance, completes the review outcome.
            self.events.load(db, row['event_id'])
            db.execute("UPDATE review_events SET status='processed',processed_at=?,last_error=NULL WHERE event_id=?", (now, row['event_id']))

    def send(self, kind, identifier):
        context = self.ensure(kind, identifier)
        column = 'event_id' if kind == 'review' else 'export_id'
        with closing(self.connect()) as db:
            db.execute('BEGIN IMMEDIATE')
            row = dict(db.execute(f'SELECT * FROM outcome_notifications WHERE {column}=?', (identifier,)).fetchone())
            if row['status'] == 'sent':
                return self.read(kind, identifier)
            if row['status'] in ('sending', 'unknown'):
                raise HTTPException(409, 'Delivery is in progress or uncertain. Check Mailpit before retrying.')
            if row['attempts'] >= LIMIT:
                raise HTTPException(409, 'Notification attempt limit reached. Inspect the saved attempts.')
            row['attempts'] += 1
            row['message_id'] = f"<ap-{row['notification_id']}-{row['attempts']}@example.invalid>"
            db.execute("UPDATE outcome_notifications SET status='sending',attempts=?,message_id=?,last_error=NULL,updated_at=? WHERE notification_id=?",
                       (row['attempts'], row['message_id'], datetime.now(timezone.utc).isoformat(), row['notification_id']))
            db.execute("INSERT INTO outcome_notification_attempts(notification_id,attempt,message_id,status) VALUES(?,?,?,'sending')",
                       (row['notification_id'], row['attempts'], row['message_id']))
            db.commit()  # The message identity survives SMTP response loss and process interruption.
        message = EmailMessage()
        message['From'], message['To'] = 'ap-results@example.invalid', 'reviewer@example.invalid'
        message['Subject'], message['Message-ID'] = context['subject'], row['message_id']
        message.set_content(context['text'] + '\nNotification ID: ' + row['notification_id'])
        status, error = self.sender(message)
        with closing(self.connect()) as db:
            db.execute('BEGIN IMMEDIATE')
            self.finish(db, row, status, error)
            db.commit()
        return self.read(kind, identifier)

    def reconcile(self, kind, identifier):
        row = self.read(kind, identifier)
        if row['status'] not in ('sending', 'unknown'):
            return row
        if datetime.fromisoformat(row['updated_at'].replace('Z', '+00:00')) > datetime.now(timezone.utc) - timedelta(seconds=60):
            raise HTTPException(409, 'Wait for the 60-second sending window before checking Mailpit.')
        host = os.environ.get('AP_MAILPIT_HOST', 'mailpit')
        if host not in ('mailpit', 'localhost', '127.0.0.1'):
            raise HTTPException(503, 'Local Mailpit required.')
        url = f'http://{host}:8025/api/v1/search?query=' + quote('message-id:' + row['message_id'].strip('<>'))
        try:
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
            with opener.open(url, timeout=10) as response:
                result = json.load(response)
            found = result.get('messages', [])
        except (OSError, ValueError):
            raise HTTPException(503, 'Mailpit verification unavailable. Notification remains uncertain.') from None
        # Absence is not proof of failure (Mailpit retention/deletion); never resend automatically.
        status, error = ('sent', None) if len(found) == 1 and found[0].get('MessageID', '').strip('<>') == row['message_id'].strip('<>') else ('unknown', 'MAILPIT_NOT_CONFIRMED')
        with closing(self.connect()) as db:
            db.execute('BEGIN IMMEDIATE')
            current = dict(db.execute('SELECT * FROM outcome_notifications WHERE notification_id=?', (row['notification_id'],)).fetchone())
            if current['status'] in ('sending', 'unknown') and current['message_id'] == row['message_id']:
                self.finish(db, row, status, error)
            db.commit()
        return self.read(kind, identifier)

    def dispatch_review(self, event_id):
        with closing(self.connect()) as db:
            event, _, _ = self.events.load(db, event_id)
            run = db.execute("SELECT result_json FROM intake_runs WHERE json_extract(result_json,'$.invoice_id')=? ORDER BY rowid DESC LIMIT 1",
                             (event['invoice_id'],)).fetchone()
            if run and json.loads(run['result_json'])['source'].get('notification_mode') == 'batch':
                # The batch summary records delivery; never fabricate a sent per-invoice notice.
                return {**self.events.read(event_id), 'notification_mode': 'batch'}
        if not os.environ.get('AP_REVIEW_EVENT_URL'):
            return
        self.ensure('review', event_id)
        try:
            return self.events.deliver(event_id)
        except HTTPException:
            # The decision/outbox is durable; an explicit retry exposes the concrete error.
            return self.events.read(event_id)

    def dispatch_batch(self, export_id):
        url, token = os.environ.get('AP_BATCH_EVENT_URL', ''), os.environ.get('AP_REVIEW_EVENT_TOKEN', '')
        if not url:
            return
        self.ensure('batch', export_id)
        parsed = urlparse(url)
        if not token or parsed.scheme != 'http' or parsed.hostname not in ('n8n', 'localhost', '127.0.0.1') or parsed.username or parsed.password or parsed.query or parsed.fragment:
            raise HTTPException(503, 'Configure the local batch webhook and credential.')
        now = datetime.now(timezone.utc)
        with closing(self.connect()) as db:
            db.execute('BEGIN IMMEDIATE')
            row = dict(db.execute('SELECT * FROM outcome_notifications WHERE export_id=?', (export_id,)).fetchone())
            if row['status'] == 'sent':
                return self.read('batch', export_id)
            if row['delivery_status'] == 'delivering' and datetime.fromisoformat(row['delivery_at']) > now - timedelta(seconds=60):
                raise HTTPException(409, 'Batch notification delivery is in progress.')
            if row['delivery_attempts'] >= LIMIT:
                raise HTTPException(409, 'Batch delivery attempt limit reached.')
            attempt = row['delivery_attempts'] + 1
            db.execute("UPDATE outcome_notifications SET delivery_status='delivering',delivery_attempts=?,delivery_at=?,delivery_error=NULL WHERE export_id=?", (attempt, now.isoformat(), export_id))
            db.commit()
        try:
            code = send_event(url, token, {'export_id': export_id})
            status, error = ('accepted', None) if 200 <= code < 300 else ('failed', f'HTTP_{code}')
        except OSError:
            status, error = 'unknown', 'TRANSPORT_UNCONFIRMED'
        with closing(self.connect()) as db:
            db.execute("UPDATE outcome_notifications SET delivery_status=?,delivery_error=? WHERE export_id=? AND delivery_attempts=? AND delivery_status='delivering'",
                       (status, error, export_id, attempt))
            db.commit()
        return self.read('batch', export_id)


def register_outcomes(app, connect, root):
    service = Outcomes(connect, root)

    @app.get('/static/outcome_notifications.js')
    def script():
        return FileResponse(Path(__file__).with_name('outcome_notifications.js'), media_type='text/javascript', headers={'Cache-Control': 'no-store'})

    @app.get('/api/ap/outcomes/{kind}/{identifier}')
    def resolve(kind: Kind, identifier: UUID, request: Request):
        protect_event(request)
        context = service.context(kind, str(identifier))
        return {key: context[key] for key in ('kind', 'id', 'category')}

    @app.post('/api/ap/outcomes/{kind}/{identifier}/notify')
    def notify(kind: Kind, identifier: UUID, request: Request):
        protect_event(request)
        result = service.send(kind, str(identifier))
        if result['status'] != 'sent':
            raise HTTPException(503, {'notification_id': result['notification_id'], 'status': result['status'], 'error': result['last_error']})
        return result

    @app.get('/api/ap/result-notifications/{kind}/{identifier}')
    def read(kind: Kind, identifier: UUID):
        return service.read(kind, str(identifier))

    @app.post('/api/ap/result-notifications/{kind}/{identifier}/{action}')
    def recover(kind: Kind, identifier: UUID, action: Literal['retry', 'check'], request: Request):
        protect_write(request)
        identifier = str(identifier)
        if action == 'check':
            return service.reconcile(kind, identifier)
        # Explicit local notification retry never regenerates Excel or changes a decision.
        return service.send(kind, identifier)

    return service
